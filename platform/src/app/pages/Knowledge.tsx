function Onboarding({ me }: { me: Me }) {
  const steps: string[] = [];
  if (can(me, 'users.manage')) steps.push('Откройте «Организации» и пригласите сотрудников: для каждого выберите роль; при необходимости настройте «Видимость» и закрепите машины.');
  if (can(me, 'machines.create')) steps.push('На странице «Парк» добавьте машину («+ Машина»), укажите тип, для агротехники — объём бака и ширину захвата.');
  if (can(me, 'sources.manage')) steps.push('Подключите источник данных: «+ Трекер по IMEI», «+ Traccar Client» или «+ Телефон (ссылка)» на странице машины. Готовая платформа — в «Подключениях».');
  if (can(me, 'stand.view')) steps.push('Посмотрите «Стенд»: как пакеты трекеров идут к серверу и что появляется в ITles. Привяжите свободный трекер стенда к машине — архив догрузится.');
  if (sees(me, 'history')) steps.push('Откройте машину и подвигайте ползунок таймлайна: маркер покажет, где она была в любой момент.');
  if (can(me, 'service.manage')) steps.push('Заполните план ТО (интервалы по моточасам) и отмечайте выполненное обслуживание.');
  if (can(me, 'readings.enter')) steps.push('Раз в неделю вносите показание счётчика моточасов с фото — это эталон для всех оценок.');
  if (sees(me, 'faults')) steps.push('Следите за красными кодами ошибок (DTC) в парке и на странице машины.');
  if (can(me, 'trash.view')) steps.push('Удалённое можно вернуть из «Корзины» в течение 30 дней; кто что менял — в «Журнале».');
  if (can(me, 'settings.manage')) steps.push('В «Настройках» выпустите ключ для своего шлюза и управляйте демо-доступом.');
  if (!steps.length) steps.push('Смотрите данные своих машин в «Парке»; ваш администратор может открыть дополнительные разделы.');
  const hidden = ALL_BLOCKS.filter((b) => !sees(me, b));
  return (
    <div className="card space-y-3 border-primary/30 p-5">
      <h2 className="text-lg font-bold">Быстрый старт: {me.role_label.toLowerCase()}</h2>
      <p className="text-sm text-muted-foreground">{ROLES[me.role].summary}.</p>
      <ol className="list-decimal space-y-1 pl-5 text-sm">{steps.map((s) => <li key={s}>{s}</li>)}</ol>
      <div className="text-xs text-muted-foreground">
        Вам видны: {me.blocks.map((b) => BLOCKS[b].label.toLowerCase()).join(', ') || 'ничего'}.
        {hidden.length ? ` Скрыто: ${hidden.map((b) => BLOCKS[b].label.toLowerCase()).join(', ')}.` : ''}
      </div>
    </div>
  );
}

export function Knowledge({ me }: { me: Me }) {
  const [q, setQ] = useState('');
  const [all, setAll] = useState(false);
  const mine = AUD[me.role];
  const list = useMemo(
    () => SECTIONS.filter((s) => (all || mine.includes(s.aud)) && (!q || s.title.toLowerCase().includes(q.toLowerCase()))),
    [q, all, me.role],
  );
  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold">База знаний</h1>
          <p className="text-sm text-muted-foreground">Разделы подобраны для вашей роли. Суперадминистратор видит всё, оператор — только то, что нужно в кабине.</p>
        </div>
        <div className="flex items-center gap-2">
          <input className="input w-52" placeholder="Поиск по разделам" value={q} onChange={(e) => setQ(e.target.value)} />
          <label className="flex items-center gap-1 text-xs text-muted-foreground">
            <input type="checkbox" checked={all} onChange={(e) => setAll(e.target.checked)} /> все разделы
          </label>
        </div>
      </div>
      <Onboarding me={me} />
      <div className="grid gap-4 lg:grid-cols-[220px_1fr]">
        <nav className="card hidden h-fit space-y-0.5 p-3 text-sm lg:block">
          {list.map((s) => (
            <a key={s.id} href={`#/kb`} onClick={(e) => { e.preventDefault(); document.getElementById('kb-' + s.id)?.scrollIntoView({ behavior: 'smooth' }); }} className="block rounded-md px-2 py-1 text-muted-foreground hover:bg-accent hover:text-foreground">
              {s.title}
            </a>
          ))}
        </nav>
        <div className="space-y-4">
          {list.map((s) => (
            <section key={s.id} id={'kb-' + s.id} className="card kb space-y-2 p-5 text-sm leading-relaxed">
              <h2 className="text-base font-bold">{s.title}</h2>
              {s.body(me)}
            </section>
          ))}
          <p className="text-xs text-muted-foreground">Параметров в справочнике датчиков: {Object.keys(SENSORS).length}. Полная инструкция с ценами и схемами подключения — PDF в репозитории (docs/guide).</p>
        </div>
      </div>
    </div>
  );
}
